n = int(input("Nhap n: "))
tong_nghich_dao = 0
for i in range(1, n + 1):
    tong_nghich_dao = tong_nghich_dao + 1 / i
print("Tong nghich dao cua", n, "so nguyen dau tien la:", tong_nghich_dao)


# Đầu vào:
# Nhap n: 5
# Đầu ra:
# Tong nghich dao cua 5 so nguyen dau tien la: 2.283333333333333

